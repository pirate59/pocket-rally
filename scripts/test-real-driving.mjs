assert(downhill.speed>uphill.speed+3,'Elevation must affect momentum');
const backwards=run({...car(20),heading:Math.PI},1,{p:{tx:0,tz:1,slope:.25}});
assert(Math.abs(backwards.vz-uphill.vz)<.01,'Slope force is independent of which way the car faces');
const air=run({...car(),airborne:true},1,{throttle:1,steer:1,brake:true});
assert.equal(air.heading,0);assert(air.speed<=20,'No tyre forces in the air');
