assert(released.speed>28,'Boost release must preserve momentum instead of clamping speed');
assert(run(car(0),3,{throttle:-1}).speed<-2,'Reverse remains usable');
const turning=run({...car(20),vx:3},dt),powered=run({...car(20),vx:3,boosting:true},dt,{throttle:1});
